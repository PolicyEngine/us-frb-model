"""Preview: the published experiments started at the October 2026 data edge.

Every published experiment shocks in 2026Q1. Under the October 2026 LONGBASE
2026Q1-Q2 are history, so those shocks start two quarters before the data
edge (VALIDATION.md, "Data vintage and the window"). Moving the published
window is a separate decision for the repo owner. This script shows what it
would change: the same three VAR scenarios (scripts/scenarios.py: monetary
100bp rate rise, egfe_aerr +1% and trp_aerr +2pp tax rise, each for one
quarter) solved over 20 quarters from 2026Q1
(as published) and from 2026Q3 (the first projected quarter).

INFORMATIONAL ONLY. Nothing here is gated against a published band, and the
2026Q3 runs are NOT cross-validated against pyfrbus (no vendor reference
exists for that window). The 2026Q1 monetary run is checked against the
committed pyfrbus reference as a control.

Usage:
    uv run python scripts/window_2026q3_preview.py [--out DIR]
writes results/window_2026q3_preview.{json,md}.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))

import scenarios  # noqa: E402

from frbus import Frbus, load_data  # noqa: E402

MODEL_XML = REPO / "vendor" / "pyfrbus_package" / "models" / "model.xml"
LONGBASE = REPO / "vendor" / "data_only_package" / "LONGBASE.TXT"
VENDOR_MONETARY = REPO / "tests" / "data" / "vendor_shock_2026q1_2030q4.csv"
STARTS = ("2026Q1", "2026Q3")
LABEL = "informational; 2026Q3 runs not cross-validated against pyfrbus; not gated"


def _ext(s: pd.Series, how: str, start: pd.Period) -> dict:
    q = s.idxmin() if how == "min" else s.idxmax()
    return {
        "value": round(float(s[q]), 4),
        "quarter": str(q),
        "quarter_after_shock": int((q - start).n) + 1,
    }


def run(model: Frbus, longbase: pd.DataFrame, name: str, start: str) -> tuple[dict, pd.DataFrame]:
    s = pd.Period(start)
    e = s + 19
    data = longbase.copy()
    scenarios.set_policy(name, data, s, e)
    base = model.init_trac(s, e, data)
    adds = base.copy()
    scenarios.apply_shock(name, adds, s, e)
    sim = model.solve(s, e, adds)
    b, x = base.loc[s:e], sim.loc[s:e]
    gdp = 100 * (x["xgdp"] / b["xgdp"] - 1)
    # contractionary shocks: a funds-rate rise and a tax rise (trp_aerr +2pp)
    sign = -1 if name in ("monetary", "taylor_noninertial", "tax_trp") else +1
    gdp_how, lur_how = ("min", "max") if sign < 0 else ("max", "min")
    summary = {
        "window": [str(s), str(e)],
        "rff_impact": round(float(x["rff"].iloc[0] - b["rff"].iloc[0]), 4),
        "xgdp_pct_peak": _ext(gdp, gdp_how, s),
        "xgap2_peak": _ext(x["xgap2"] - b["xgap2"], gdp_how, s),
        "lur_peak": _ext(x["lur"] - b["lur"], lur_how, s),
        "picxfe_peak": _ext(x["picxfe"] - b["picxfe"], "min" if sign < 0 else "max", s),
        "baseline_at_start": {
            v: round(float(b[v].iloc[0]), 3) for v in ("rff", "lur", "xgap2", "picxfe")
        },
    }
    return summary, sim


def compute(longbase: pd.DataFrame) -> dict:
    model = Frbus(str(MODEL_XML))
    out: dict = {
        "label": LABEL,
        "data_edge": "2026Q2 (HISTDATA.TXT, October 2026 LONGBASE)",
        "scenarios": {},
    }
    for name in ("monetary", "fiscal_egfe", "tax_trp"):
        out["scenarios"][name] = {}
        for start in STARTS:
            summary, sim = run(model, longbase, name, start)
            out["scenarios"][name][start] = summary
            if name == "monetary" and start == "2026Q1":
                vendor = load_data(str(VENDOR_MONETARY))
                diff = (sim.loc[vendor.index, vendor.columns] - vendor).abs().to_numpy()
                out["control_2026q1_monetary_vs_pyfrbus_max_abs"] = float(f"{np.nanmax(diff):.1e}")
    return out


def render(r: dict) -> str:
    out = [
        "# Preview: published experiments started at the data edge (2026Q3)",
        "",
        "Generated by `scripts/window_2026q3_preview.py`; do not edit by hand. "
        f"**{r['label']}.** Data edge: {r['data_edge']}. Control: the 2026Q1 "
        "monetary run matches the committed pyfrbus reference to "
        f"{r['control_2026q1_monetary_vs_pyfrbus_max_abs']:.1e}.",
        "",
        "| scenario | quantity | from 2026Q1 (published) | from 2026Q3 | change |",
        "|---|---|---|---|---|",
    ]
    names = {
        "xgdp_pct_peak": "real GDP peak response (%)",
        "xgap2_peak": "output gap peak response (pp)",
        "lur_peak": "unemployment peak response (pp)",
        "picxfe_peak": "core PCE (q/q) peak response (pp)",
    }
    for sc, runs in r["scenarios"].items():
        a, b = runs["2026Q1"], runs["2026Q3"]
        for k, label in names.items():
            va, vb = a[k], b[k]
            change = (
                f"{100 * (vb['value'] / va['value'] - 1):+.1f}%"
                if abs(va["value"]) >= 1e-3
                else "n/a (response < 0.001)"
            )
            out.append(
                f"| {sc} | {label} | {va['value']:+.4f} (q{va['quarter_after_shock']}) "
                f"| {vb['value']:+.4f} (q{vb['quarter_after_shock']}) | {change} |"
            )
    out += [
        "",
        "Baseline at the shock quarter (levels): "
        + "; ".join(
            f"{s}: "
            + ", ".join(
                f"{k} {v}" for k, v in r["scenarios"]["monetary"][s]["baseline_at_start"].items()
            )
            for s in STARTS
        )
        + ".",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", type=Path, default=REPO / "results")
    args = p.parse_args(argv)
    r = compute(load_data(str(LONGBASE)))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "window_2026q3_preview.json").write_text(json.dumps(r, indent=2) + "\n")
    md = render(r)
    (args.out / "window_2026q3_preview.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
